import fs from "node:fs";
import crypto from "node:crypto";
const source = new URL(
  "../../../contracts/generated/openapi.json",
  import.meta.url,
);
const raw = fs.readFileSync(source, "utf8"),
  api = JSON.parse(raw);
const literal = (v) => JSON.stringify(v);
function type(s) {
  if (s.$ref) return `Schemas[${literal(s.$ref.split("/").at(-1))}]`;
  if (s.const !== undefined) return literal(s.const);
  if (s.enum) return s.enum.map(literal).join(" | ");
  if (s.anyOf || s.oneOf)
    return "(" + (s.anyOf || s.oneOf).map(type).join(" | ") + ")";
  if (s.allOf) return s.allOf.map(type).join(" & ");
  if (s.type === "array" && s.prefixItems)
    return "[" + s.prefixItems.map(type).join(", ") + "]";
  if (s.type === "array") return `Array<${type(s.items || {})}>`;
  if (s.type === "object" || s.properties) {
    let props = Object.entries(s.properties || {})
      .map(
        ([k, v]) =>
          `${literal(k)}${(s.required || []).includes(k) ? "" : "?"}: ${type(v)};`,
      )
      .join("\n");
    let result = `{\n${props}\n}`;
    if (s.additionalProperties && typeof s.additionalProperties === "object")
      result = props
        ? `(${result} & Record<string, ${type(s.additionalProperties)}>)`
        : `Record<string, ${type(s.additionalProperties)}>`;
    return result;
  }
  return (
    {
      string: "string",
      number: "number",
      integer: "number",
      boolean: "boolean",
      null: "null",
    }[s.type] || "unknown"
  );
}
const hash = crypto.createHash("sha256").update(raw).digest("hex");
const types = `// Generated by scripts/generate-api.mjs. Do not edit. OpenAPI SHA256: ${hash}\nexport interface Schemas {\n${Object.entries(
  api.components.schemas,
)
  .map(([k, v]) => `${literal(k)}: ${type(v)};`)
  .join("\n")}\n}\n`;
const schema = JSON.stringify({ $id: "waydex-v2", components: api.components });
for (const [name, content] of [
  ["schema.ts", types],
  ["validation.json", schema],
]) {
  const file = new URL("../src/api/generated/" + name, import.meta.url);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content)
      throw Error("Generated API is stale: " + name);
  } else fs.writeFileSync(file, content);
}
console.log("API types and runtime schemas match OpenAPI " + hash.slice(0, 12));
