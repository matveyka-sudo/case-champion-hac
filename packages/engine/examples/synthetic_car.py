"""Synthetic car replay only; no actual city, server or measured minimum."""

import json
from datetime import UTC, datetime

from a2_engine import (
    CarInputs,
    RoadBuild,
    RoadCoordinate,
    RoadEndpoint,
    RoadRequest,
    RoadResponse,
    UrbanArea,
    UrbanContext,
    UrbanDestination,
    UrbanPoint,
    UrbanPopulationCoverage,
    UrbanVersions,
    analyze_car_responses,
    load_urban_config,
    load_urban_journey_rules,
    plan_car_routes,
)


def synthetic_inputs() -> CarInputs:
    build = RoadBuild(
        "test-snapshot",
        "test-source",
        "test-build",
        "test-graph",
        "test-profile",
        "auto",
        '{"speed_types":["freeflow"]}',
        ("synthetic-build-proof",),
    )
    versions = UrbanVersions(
        build.snapshot_id,
        build.graph_version,
        "calendar",
        "population",
        "geometry",
        "a2-methodology-v3",
        "test-config",
        "static:" + build.build_id,
    )
    context = UrbanContext(
        "city", "city", datetime(2026, 11, 9, 8, tzinfo=UTC), "static", versions, "test-search"
    )
    point = UrbanPoint(
        "A",
        "cell-A",
        "physical-A",
        "access-A",
        20,
        "city",
        90,
        2026,
        "synthetic",
        ("test-population",),
    )
    destination = UrbanDestination(
        "school",
        "school",
        frozenset({"school"}),
        "access-school",
        "city",
        True,
        True,
        ("test-catalog",),
        physical_node_id="physical-school",
    )
    entry = RoadEndpoint(
        build,
        point.origin_node_id,
        point.access_node_id,
        RoadCoordinate(20, 54),
        "test-entry",
        "entry",
        60,
        ("test-car-entry-proof",),
    )
    exit = RoadEndpoint(
        build,
        "physical-school",
        destination.access_node_id,
        RoadCoordinate(20.01, 54.01),
        "test-exit",
        "exit",
        120,
        ("test-car-exit-proof",),
    )
    return CarInputs(
        context,
        (point,),
        (destination,),
        ((point.point_id, entry),),
        ((destination.destination_id, exit),),
        UrbanArea("city", 200, "geometry", ("test-area",)),
        UrbanPopulationCoverage(context, True, 0, ("test-population",), frozenset({"A"})),
        (("school", True, ("test-catalog",)),),
        "UTC",
    )


def synthetic_response(
    request: RoadRequest, seconds: float = 1620, *, proven: bool = True
) -> RoadResponse:
    # Independent fake executor attestations, never generated by the normalizer.
    body = {
        "id": request.request_id,
        "trip": {
            "status": 0,
            "units": "kilometers",
            "locations": [
                dict(lon=e.coordinate.lon, lat=e.coordinate.lat)
                for e in (request.origin, request.destination)
            ],
            "summary": {"time": seconds, "length": 10, "has_ferry": False},
            "legs": [
                {
                    "summary": {"time": seconds, "length": 10, "has_ferry": False},
                    "maneuvers": [
                        {
                            "travel_mode": "drive"
                            if request.origin.build.costing == "auto"
                            else "pedestrian"
                        }
                    ],
                }
            ],
        },
    }
    return RoadResponse(
        request.request_id,
        request.payload_hash,
        request.origin.build.profile_hash,
        "response",
        json.dumps(body),
        ("test-response",),
        request.origin.coordinate,
        request.destination.coordinate,
        ("test-actual-endpoints",),
        ("synthetic-exhaustive-minimum",) if proven else (),
        (),
        proven,
    )


def main() -> None:
    inputs = synthetic_inputs()
    plan = plan_car_routes(inputs, categories=("school",))
    output = analyze_car_responses(
        plan,
        (synthetic_response(plan.requests[0]),),
        selected_categories={"school": "high"},
        config=load_urban_config(),
        rules=load_urban_journey_rules(),
    )
    category = output.analysis.modes[0].points[0].categories[0]
    assert category.index.value == 50
    assert category.best is not None
    timing = category.best.journey
    assert (timing.total_seconds, timing.walking_seconds, timing.riding_seconds) == (
        1800,
        180,
        1620,
    )
    print("SYNTHETIC car: total=1800 walk=180 ride=1620 index=50; geometry unavailable")


if __name__ == "__main__":
    main()
